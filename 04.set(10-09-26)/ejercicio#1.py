# EJERCICIO 1 — SETS

# Dada una tupla de números, devuelve un set que contenga
# # únicamente los valores diferentes.
# #
# # No utilices ningún método de eliminación manual de duplicados.
# #
# # Ejemplo:
# #
# # entrada:
# # (4, 2, 4, 7, 2, 9, 7, 7)
# #
# # salida:
# # {2, 4, 7, 9}
# 

numeros = (4, 2, 4, 7, 2, 9, 7, 7)

numeroset = set(numeros)

print(numeroset)




